/**
 * 把 packages/accio-mcp（零依赖 ESM，多文件）合并成一个自包含单文件
 * plugin/clis/geoly.mjs，供 Accio Work 的 node-cli 源直接跑——
 * Accio 只拷入口文件、不带同目录 src/，所以入口不能有任何相对 import（否则 ERR_MODULE_NOT_FOUND）。
 *
 * 合并规则：
 *  - node: 内置 import 收集去重后提到顶部；node:module(createRequire) 丢弃（只用于读 package.json）
 *  - 模块间相对 import / export 关键字剥除（全部并入同一作用域）
 *  - config 里读 package.json 的 VERSION 内联成构建期字面量
 *  - main.mjs 的动态 import('./oauth.mjs' | './bridge.mjs') 整行删除（符号已在同作用域）
 * 用法：node scripts/bundle-cli.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkgPath = join(root, 'packages/accio-mcp/package.json');
const version = JSON.parse(readFileSync(pkgPath, 'utf8')).version;

const order = ['config', 'credentials', 'oauth', 'bridge', 'invoke', 'main'];
const nodeImports = new Set();
const bodies = [];

/** 处理单个模块源码：剥 import/export、内联 VERSION、删动态本地 import。 */
function processModule(src, isConfig) {
  // 先把多行 named import 归一成单行，逐行过滤器才能整体识别删除
  src = src.replace(
    /import\s*\{([\s\S]*?)\}\s*from\s*(['"][^'"]+['"]);?/g,
    (_, names, from) => `import { ${names.replace(/\s+/g, ' ').replace(/,\s*$/, '').trim()} } from ${from};`
  );
  const out = [];
  for (let line of src.split('\n')) {
    const t = line.trim();
    // node: 内置 import → 收集（createRequire 那条丢弃）
    const nm = t.match(/^import\s+.*from\s+['"](node:[^'"]+)['"];?$/);
    if (nm) {
      if (nm[1] !== 'node:module') nodeImports.add(t);
      continue;
    }
    // 本地相对 import（静态）→ 删
    if (/^import\s+.*from\s+['"]\.\.?\//.test(t)) continue;
    // 本地动态 import 行（const { x } = await import('./y.mjs');）→ 删，符号已在同作用域
    if (/await import\(\s*['"]\.\.?\//.test(t)) continue;
    if (isConfig) {
      if (/createRequire\(import\.meta\.url\)/.test(t)) continue;
      if (/const pkg = require\(/.test(t)) continue;
      if (/export const VERSION = pkg\.version;?/.test(t)) {
        out.push(`const VERSION = ${JSON.stringify(version)};`);
        continue;
      }
    }
    // 去掉行首 export
    line = line.replace(/^(\s*)export\s+/, '$1');
    out.push(line);
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

for (const name of order) {
  const src = readFileSync(join(root, `packages/accio-mcp/src/${name}.mjs`), 'utf8');
  bodies.push(`// ==== ${name}.mjs ====\n${processModule(src, name === 'config')}`);
}

// cli 入口：剥 import 行，保留 main() 调用
const cliSrc = readFileSync(join(root, 'packages/accio-mcp/bin/cli.mjs'), 'utf8')
  .split('\n')
  .filter((l) => !/^#!/.test(l) && !/^import\s+.*from\s+['"]\.\.?\//.test(l))
  .join('\n')
  .trim();

const banner = '#!/usr/bin/env node\n// AUTO-GENERATED by scripts/bundle-cli.mjs — do not edit. Source: packages/accio-mcp/';
const output = [
  banner,
  [...nodeImports].sort().join('\n'),
  bodies.join('\n\n'),
  '// ==== cli entry ====',
  cliSrc,
].join('\n\n') + '\n';

const outPath = join(root, 'plugin/clis/geoly.mjs');
writeFileSync(outPath, output, 'utf8');
console.log(`bundled → plugin/clis/geoly.mjs (${output.length} bytes, version ${version})`);
